function kf = KalmanFilterDesign(A,B,C,G,Q,R) %%Code generated by claude - it was fed the design covered in the lectures
% Design of a discrete-time Kalman filter.
%
% System:
%   x_{k+1} = A*x_k + B*u_k + G*w_k
%   y_k     = C*x_k + v_k
%
%   w_k ~ N(0,Q)
%   v_k ~ N(0,R)

% Solve stationary Riccati equation
[~,P,~] = dlqe(A,G,C,Q,R);

% Stationary measurement update
Re  = C*P*C' + R;
Kfx = P*C'/Re;

% Stationary filtered covariance
Pf = P - Kfx*Re*Kfx';

% Store model
kf.A  = A;
kf.B  = B;
kf.C  = C;
kf.Qw = G*Q*G';
kf.R  = R;

kf.P   = P;
kf.Pf  = Pf;
kf.Re  = Re;
kf.Kfx = Kfx;

end